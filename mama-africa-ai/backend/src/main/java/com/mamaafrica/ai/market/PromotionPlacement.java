package com.mamaafrica.ai.market;

/** Where the website renders a promotion. */
public enum PromotionPlacement {
    /** The thin strip across the top of every page. */
    ANNOUNCEMENT_STRIP,
    /** The large panel at the head of the store page. */
    STORE_HERO,
    /** A small badge drawn on matching product cards. */
    PRODUCT_BADGE,
    /** The pop-up shown to first-time visitors. */
    WELCOME_POPUP
}
